"""Build preview.html from the running site.

preview.html is a single file you can open straight from disk to click through the
whole site (both languages, every article) without starting a server. It is generated,
never edited by hand: when the site changes, start the site and run this again.

    python tools/build_preview.py                       # site at http://localhost:8080
    python tools/build_preview.py --base http://localhost:18080

How it works
- Loads every top-level page in both languages, then follows same-site page links (articles).
- Each page is kept as a full HTML document and shown in one iframe (srcdoc), so the
  page's own CSS and JS run as on the site. The address is a hash: preview.html#/blog/solo-trust
- CSS, JS and media are not copied: links point at the real files in this repo
  (backend/src/main/resources/static/..., content/articles/<slug>/media/...),
  so preview.html must stay at the repo root.
- Forms do not submit in the preview, and /survey/verify?pick=... does not preselect an option.
"""
import argparse
import html
import json
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "preview.html"
STATIC = "backend/src/main/resources/static/"
# Top-level pages (one controller each). Some are not linked from the nav, so list them all;
# articles are found by following the blog lists. No address that redirects (e.g. /survey, a 301 to
# /survey/verify): fetch() skips redirects, and every START page must load.
TOP = ["/about", "/products", "/products/verify", "/products/content", "/cases", "/contact", "/resources", "/survey/verify", "/survey/content", "/blog"]
START = TOP + ["/en" + p for p in TOP]
NOT_PAGES = ("/css/", "/js/", "/media/", "/articles/")

# Runs inside every page: site links change the preview route instead of loading a URL.
PAGE_SCRIPT = """<script>
document.addEventListener('click', function (e) {
  var a = e.target.closest && e.target.closest('a[href^="#/"]');
  if (!a) return;
  e.preventDefault();
  parent.postMessage({ previewRoute: a.getAttribute('href').slice(1) }, '*');
}, true);
document.addEventListener('submit', function (e) {
  e.preventDefault();
  alert('預覽不會送出表單。 / Forms do not submit in the preview.');
}, true);
</script>"""

SHELL = """<!DOCTYPE html>
<html lang="zh-Hant-TW">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>麒麟魚 Qilinfish Studio — Preview</title>
<!-- Generated by tools/build_preview.py from __BASE__ — do not edit by hand. -->
<style>html,body{margin:0;height:100%;background:#0a0a0c}iframe{display:block;width:100%;height:100%;border:0}</style>
</head>
<body>
<iframe id="page" title="preview"></iframe>
<script id="pages" type="application/json">__PAGES__</script>
<script>
(function () {
  var pages = JSON.parse(document.getElementById('pages').textContent);
  var frame = document.getElementById('page');
  function show() {
    var route = location.hash.slice(1).split('?')[0] || '/about';
    var page = pages[route] || pages['/about'];
    frame.srcdoc = page.html;
    document.title = page.title + ' — Preview';
  }
  window.addEventListener('message', function (e) {
    if (e.data && e.data.previewRoute) location.hash = e.data.previewRoute;
  });
  window.addEventListener('hashchange', show);
  show();
})();
</script>
</body>
</html>
"""


def fetch(base, path):
    try:
        with urllib.request.urlopen(base + path, timeout=30) as r:
            if r.status != 200 or "text/html" not in r.headers.get("Content-Type", ""):
                return None
            if r.geturl().rstrip("/") != (base + path).rstrip("/"):
                return None  # redirected: the target is crawled under its own path
            return r.read().decode("utf-8")
    except urllib.error.HTTPError:
        return None


def page_links(doc):
    for href in re.findall(r'href="(/[^"#?]*)', doc):
        if href.startswith(NOT_PAGES) or "." in href.rsplit("/", 1)[-1]:
            continue
        yield href.rstrip("/") or "/"


def rewrite(doc, routes):
    # CSS / JS / media: point at the real files in the repo (query strings dropped).
    doc = re.sub(r'((?:href|src)=")/(css|js)/([^"?]+)(\?[^"]*)?"', r'\1' + STATIC + r'\2/\3"', doc)
    doc = re.sub(r'((?:src|poster|href)=")/media/', r'\1' + STATIC + "media/", doc)
    doc = re.sub(r'((?:src|poster|href)=")/articles/([^/"]+)/media/', r'\1content/articles/\2/media/', doc)

    # Page links that exist in the preview become hash routes. A query string stays in the
    # hash but the page cannot read it (srcdoc has no location.search): /survey/verify?pick= does not preselect.
    def link(m):
        path = m.group(2).rstrip("/") or "/"
        return f'{m.group(1)}#{path}{m.group(3) or ""}"' if path in routes else m.group(0)
    doc = re.sub(r'(href=")(/[^"#?]*)(\?[^"#]*)?"', link, doc)
    return doc.replace("</body>", PAGE_SCRIPT + "\n</body>", 1)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--base", default="http://localhost:8080")
    base = ap.parse_args().base.rstrip("/")

    raw, todo, seen = {}, list(START), set()
    while todo:
        path = todo.pop(0)
        if path in seen:
            continue
        seen.add(path)
        doc = fetch(base, path)
        if doc is None:
            continue
        raw[path] = doc
        todo.extend(p for p in page_links(doc) if p not in seen)
    if not all(p in raw for p in START):
        sys.exit(f"could not load {START} from {base} — is the site running?")

    routes = set(raw)
    pages = {}
    for path in sorted(routes):
        title = re.search(r"<title>(.*?)</title>", raw[path], re.S)
        pages[path] = {"title": html.unescape(title.group(1).strip()) if title else path,
                       "html": rewrite(raw[path], routes)}

    data = json.dumps(pages, ensure_ascii=False).replace("</", "<\\/")
    OUT.write_text(SHELL.replace("__BASE__", base).replace("__PAGES__", data), encoding="utf-8")
    print(f"{OUT.name}: {len(pages)} pages, {OUT.stat().st_size // 1024} KB")
    for path in sorted(pages):
        print("  #" + path)


if __name__ == "__main__":
    main()
